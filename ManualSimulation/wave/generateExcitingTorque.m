% generateExcitingTorque.m
% Builds the wave struct for a run: loads the capytaine-derived excitation
% coefficients (local sub-function getExcited, reads oswec_new2.nc),
% generates the wave spectrum, computes average wave power, and generates
% the excitation torque time series.
% Calls: wave/getSpectrum.m, calculateWavePower.m, getTorqueTimeSeries.m
% Called by: main_WEC_Simulation.m, parameters/optimizePressure.m,
%   parameters/sizeCylinderArea.m, diagnostics/checkAstarVsBruteForce.m,
%   checkEnergyBalance.m, checkMPC_EHA.m, checkTerminalCost.m,
%   validatePhase2Subset.m
function wave = generateExcitingTorque(params)
wave = struct();

% Load hydrodynamic data
[wave.w,wave.Kexc] = getExcited;
        % This was generated by capytaine and assumes the flap can only
        % rotate about the hinge point (as opposed to wecsims
        % documentation, which calculates hydro coefficients assuming the
        % body can move in all degrees of freedom and them adds constraints
        % later)

% Generate Wave Spectrum(wave type dependent)
switch params.simu.waveType
    case "polychromatic"
        wave.spectrum = getSpectrum(wave.w,...
            params.simu.peakPeriod,...
            params.simu.sigWaveHeight);
    case "monochromatic"
        wave.spectrum.S_w = zeros(1,length(wave.w));
        [~,wInd] = min(abs(wave.w - 2*pi/params.simu.peakPeriod));
        wave.spectrum.S_w(wInd) = params.simu.sigWaveHeight^2;
        wave.spectrum.w = wave.w';
        wave.spectrum.dw = [0, diff(wave.w)];
end

% Calculate average wave resource
wave.avePower = calculateWavePower(params,wave);

wave.torque = getTorqueTimeSeries(params,wave);

end

